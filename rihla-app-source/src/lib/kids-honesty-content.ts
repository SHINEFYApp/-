export function pickHonestyStoryForDate(date: Date): KidsHonestyStory {
  const dayOfYear = Math.floor(
    (Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()) -
      Date.UTC(date.getUTCFullYear(), 0, 0)) /
      86400000
  );
  const index = ((dayOfYear % KIDS_HONESTY_STORIES.length) + KIDS_HONESTY_STORIES.length) % KIDS_HONESTY_STORIES.length;
  return KIDS_HONESTY_STORIES[index];
}
