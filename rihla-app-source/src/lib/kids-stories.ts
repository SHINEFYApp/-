export function pickStoryForDate(date: Date): KidsStory {
  const dayOfYear = Math.floor(
    (Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()) -
      Date.UTC(date.getUTCFullYear(), 0, 0)) /
      86400000
  );
  const index = ((dayOfYear % KIDS_STORIES.length) + KIDS_STORIES.length) % KIDS_STORIES.length;
  return KIDS_STORIES[index];
}
